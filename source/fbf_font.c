/* fbf_font.c -- lettering in the game's own styles, for the port's
 * leaderboard (fbf_ui.c).
 *
 * The game has no font: its words are pictures (GAME OVER, GET READY, the
 * score panel's MEDAL, SCORE and BEST) and its numbers are digit sprites. So
 * the port's words are drawn here the way those pictures are drawn --
 * measured on the atlas, pixel by pixel (tools/test_ui.py redraws GAME OVER,
 * the ten score digits and the panel's labels with these rules and compares):
 *
 *   TITLE   (GAME OVER, GET READY) Letters are white blocks 17 art pixels
 *           tall, 9 wide (M 15), cut by 1-pixel slits; 1 pixel between
 *           letters, 8 more for a space. Around the white, a dark edge
 *           (20,24,28): its 4 neighbours, and its diagonal ones except where
 *           the white runs on as a staircase (a bevelled corner keeps a clean
 *           diagonal); the white is copied 1 pixel down in the dark colour,
 *           with the same edge -- the letters' depth. Under it all, a soft
 *           shadow: the shape 2 pixels lower, blurred by [1 5 11 17 11 5 1]
 *           both ways, black at up to 51/255.
 *   SMALL   (the score digits) White bodies 8 tall, 5 wide, strokes 2
 *           pixels, a black edge on all 8 sides; 3 pixels from body to body.
 *   LABEL   (MEDAL, SCORE, BEST) Salmon (252,120,88) strokes 1 pixel wide,
 *           5 tall, and a pale line (240,234,161) 1 pixel under each; 1 pixel
 *           between letters.
 *
 * The letters themselves are drawn for this port in those styles: the few
 * the game has in its titles keep its shapes; the rest follow them. An art
 * pixel is 2x2 pixels of the game's 768x432 picture. MIT.
 */
