/* ---------------------------------------------------------------- common */
static const Glyph *glyph(FbfFont f, char c, int *h) {
  const Glyph *t;
  int n;
  switch (f) {
  case FBF_FONT_TITLE: t = k_title, n = (int)(sizeof k_title / sizeof *k_title), *h = T_H; break;
  case FBF_FONT_SMALL: t = k_small, n = (int)(sizeof k_small / sizeof *k_small), *h = S_H; break;
  default: t = k_label, n = (int)(sizeof k_label / sizeof *k_label), *h = L_H; break;
  }
  for (int i = 0; i < n; i++)
    if (t[i].c == c)
      return &t[i];
  return NULL;
}

static int space_of(FbfFont f) { return f == FBF_FONT_TITLE ? T_SPACE : f == FBF_FONT_SMALL ? S_SPACE : L_SPACE; }
static int gap_of(FbfFont f) { return f == FBF_FONT_SMALL ? 3 : 1; }

int fbf_font_height(FbfFont f) { return f == FBF_FONT_TITLE ? T_H : f == FBF_FONT_SMALL ? S_H : L_H; }

int fbf_font_has(FbfFont f, char c) {
  int h;
  return c == ' ' || glyph(f, c, &h) != NULL;
}

int fbf_font_width(FbfFont f, const char *text) {
  int w = 0, n = 0, h;
  for (const char *p = text; *p; p++, n++) {
    const Glyph *g = glyph(f, *p, &h);
    w += g ? (int)strlen(g->rows[0]) : space_of(f);
  }
  return n ? w + gap_of(f) * (n - 1) : 0;
}

void fbf_blend(uint8_t *d, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  if (!a)
    return;
  if (a == 255 || !d[3]) {
    d[0] = r, d[1] = g, d[2] = b, d[3] = a;
    return;
  }
  const int da = d[3] * (255 - a) / 255, oa = a + da;
  d[0] = (uint8_t)((r * a + d[0] * da + oa / 2) / oa);
  d[1] = (uint8_t)((g * a + d[1] * da + oa / 2) / oa);
  d[2] = (uint8_t)((b * a + d[2] * da + oa / 2) / oa);
  d[3] = (uint8_t)oa;
}

/* One art pixel: 2x2 of the picture, clipped. */
static void art_px(FbfCanvas *c, int ax, int ay, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  for (int dy = 0; dy < 2; dy++)
    for (int dx = 0; dx < 2; dx++) {
      const int x = ax * 2 + dx, y = ay * 2 + dy;
      if (x >= 0 && y >= 0 && x < c->w && y < c->h)
        fbf_blend(c->px + ((size_t)y * (size_t)c->w + (size_t)x) * 4, r, g, b, a);
    }
}

/* The text's bodies as a mask with a margin of m art pixels. */
typedef struct {
  uint8_t *m;
  int w, h;
} Mask;

static int mask_of(FbfFont f, const char *text, int margin, int extra_bottom, Mask *out) {
  const int gh = fbf_font_height(f);
  out->w = fbf_font_width(f, text) + 2 * margin;
  out->h = gh + 2 * margin + extra_bottom;
  out->m = calloc((size_t)out->w * (size_t)out->h, 1);
  if (!out->m)
    return -1;
  int x = margin, h;
  for (const char *p = text; *p; p++) {
    const Glyph *g = glyph(f, *p, &h);
    const int gw = g ? (int)strlen(g->rows[0]) : space_of(f);
    for (int r = 0; g && r < gh; r++)
      for (int k = 0; k < gw; k++)
        if (g->rows[r][k] == '#')
          out->m[(size_t)(margin + r) * (size_t)out->w + (size_t)(x + k)] = 1;
    x += gw + gap_of(f);
  }
  return 0;
}

static int in(const Mask *k, const uint8_t *m, int x, int y) {
  return x >= 0 && y >= 0 && x < k->w && y < k->h && m[(size_t)y * (size_t)k->w + (size_t)x];
}

/* The TITLE edge of a shape: 4 neighbours, and diagonals but at staircases. */
static void edge_title(const Mask *k, const uint8_t *b, uint8_t *out) {
  static const int d4[4][2] = {{-1, 0}, {1, 0}, {0, -1}, {0, 1}};
  static const int dg[4][2] = {{-1, -1}, {-1, 1}, {1, -1}, {1, 1}};
  for (int y = 0; y < k->h; y++)
    for (int x = 0; x < k->w; x++) {
      if (in(k, b, x, y))
        continue;
      int e = 0;
      for (int i = 0; i < 4 && !e; i++)
        e = in(k, b, x + d4[i][1], y + d4[i][0]);
      for (int i = 0; i < 4 && !e; i++) {
        const int dy = dg[i][0], dx = dg[i][1];
        const int cy = y - dy, cx = x - dx; /* the white pixel it touches corner to corner */
        if (in(k, b, cx, cy) && !in(k, b, cx + dx, cy - dy) && !in(k, b, cx - dx, cy + dy))
          e = 1;
      }
      out[(size_t)y * (size_t)k->w + (size_t)x] |= (uint8_t)e;
    }
}

static void draw_title(FbfCanvas *c, const char *text, int px, int py) {
  enum { M = 5, EXTRA = 3 };
  Mask k;
  if (mask_of(FBF_FONT_TITLE, text, M, EXTRA, &k))
    return;
  const size_t n = (size_t)k.w * (size_t)k.h;
  uint8_t *low = calloc(n, 1), *dark = calloc(n, 1);
  int *h1 = calloc(n, sizeof(int)), *sh = calloc(n, sizeof(int));
  if (!low || !dark || !h1 || !sh)
    goto done;
  for (int y = 1; y < k.h; y++) /* the white, 1 lower: the depth */
    memcpy(low + (size_t)y * (size_t)k.w, k.m + (size_t)(y - 1) * (size_t)k.w, (size_t)k.w);
  edge_title(&k, k.m, dark);
  edge_title(&k, low, dark);
  for (size_t i = 0; i < n; i++)
    dark[i] = (uint8_t)((dark[i] || low[i]) && !k.m[i]);
  /* the shadow: the whole shape 2 lower, blurred [1 5 11 17 11 5 1] / 51
   * each way, at up to 51/255 */
  static const int kern[7] = {1, 5, 11, 17, 11, 5, 1};
  for (int y = 0; y < k.h; y++)
    for (int x = 0; x < k.w; x++) {
      int s = 0;
      for (int i = 0; i < 7; i++) {
        const int sx = x + i - 3, sy = y - 2;
        if (sx >= 0 && sx < k.w && sy >= 0) {
          const size_t j = (size_t)sy * (size_t)k.w + (size_t)sx;
          s += kern[i] * (k.m[j] || dark[j]);
        }
      }
      h1[(size_t)y * (size_t)k.w + (size_t)x] = s;
    }
  for (int y = 0; y < k.h; y++)
    for (int x = 0; x < k.w; x++) {
      int s = 0;
      for (int i = 0; i < 7; i++) {
        const int sy = y + i - 3;
        if (sy >= 0 && sy < k.h)
          s += kern[i] * h1[(size_t)sy * (size_t)k.w + (size_t)x];
      }
      sh[(size_t)y * (size_t)k.w + (size_t)x] = s; /* of 51 * 51 */
    }
  const int ox = px / 2 - M, oy = py / 2 - M;
  for (int y = 0; y < k.h; y++)
    for (int x = 0; x < k.w; x++) {
      const size_t i = (size_t)y * (size_t)k.w + (size_t)x;
      if (k.m[i])
        art_px(c, ox + x, oy + y, 255, 255, 255, 255);
      else if (dark[i])
        art_px(c, ox + x, oy + y, 20, 24, 28, 255);
      else if (sh[i])
        art_px(c, ox + x, oy + y, 0, 0, 0, (uint8_t)((sh[i] + 25) / 51));
    }
done:
  free(k.m);
  free(low);
  free(dark);
  free(h1);
  free(sh);
}

static void draw_small(FbfCanvas *c, const char *text, int px, int py) {
  enum { M = 1 };
  Mask k;
  if (mask_of(FBF_FONT_SMALL, text, M, 0, &k))
    return;
  const int ox = px / 2 - M, oy = py / 2 - M;
  for (int y = 0; y < k.h; y++)
    for (int x = 0; x < k.w; x++) {
      if (in(&k, k.m, x, y)) {
        art_px(c, ox + x, oy + y, 255, 255, 255, 255);
        continue;
      }
      int e = 0;
      for (int dy = -1; dy <= 1 && !e; dy++)
        for (int dx = -1; dx <= 1 && !e; dx++)
          e = in(&k, k.m, x + dx, y + dy);
      if (e)
        art_px(c, ox + x, oy + y, 0, 0, 0, 255);
    }
  free(k.m);
}

static void draw_label(FbfCanvas *c, const char *text, int px, int py) {
  Mask k;
  if (mask_of(FBF_FONT_LABEL, text, 0, 1, &k))
    return;
  const int ox = px / 2, oy = py / 2;
  for (int y = 0; y < k.h; y++)
    for (int x = 0; x < k.w; x++) {
      if (in(&k, k.m, x, y))
        art_px(c, ox + x, oy + y, 252, 120, 88, 255);
      else if (in(&k, k.m, x, y - 1))
        art_px(c, ox + x, oy + y, 240, 234, 161, 255);
    }
  free(k.m);
}

void fbf_font_draw(FbfCanvas *c, FbfFont f, const char *text, int x, int y) {
  if (!text || !*text)
    return;
  switch (f) {
  case FBF_FONT_TITLE: draw_title(c, text, x, y); break;
  case FBF_FONT_SMALL: draw_small(c, text, x, y); break;
  default: draw_label(c, text, x, y); break;
  }
}
